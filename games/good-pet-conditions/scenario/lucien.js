function lines(art,source){
  return p(art,source).flatMap(beat=>{
    const result=[];let text=beat.text;
    while(text.length>65){
      const head=text.slice(0,65);
      let cut=Math.max(head.lastIndexOf('。'),head.lastIndexOf('？'),head.lastIndexOf('！'))+1;
      if(cut<20)cut=Math.max(head.lastIndexOf('、'),head.lastIndexOf('。'))+1;
      if(cut<20)cut=65;
      result.push({...beat,text:text.slice(0,cut),cue:result.length?'':beat.cue});
      text=text.slice(cut);
    }
    if(text)result.push({...beat,text,cue:result.length?'':beat.cue});
    return result;
  });
}
